-- 00012: 책 대상 — "이런 분께"를 저자가 직접 쓴다
--
-- 책 상세에는 소개글 한 덩어리뿐이라 사려는 사람이 이 책이 자기에게
-- 맞는지 알 수 없었습니다(2026-10-20). 저자가 한 줄에 한 사람씩 적고,
-- 상세 화면은 줄마다 목록 항목으로 그립니다.
--
-- 줄 단위 배열이 아니라 TEXT 하나입니다. 설정 폼은 textarea 하나로
-- 쓰고, 줄 나누기는 화면에서만 합니다. 길이 상한은 라우트가 먼저
-- 검사합니다(PUT /api/books/[bookId]).
--
-- 정책은 추가하지 않습니다. 기존 books UPDATE(소유자)가 그대로 덮습니다.
-- ============================================================

ALTER TABLE books
  ADD COLUMN audience TEXT
    CHECK (audience IS NULL OR char_length(audience) <= 1000);
